function objs(src, from, to) {
  var a = src.indexOf(from);
  if (a < 0) return [];
  var b = to ? src.indexOf(to, a) : src.length;
  var seg = src.slice(a, b < 0 ? src.length : b);
  var out = [], re = /\{\s*(?:n:\s*(?:'([^']*)'|"([^"]*)"|(\d+))\s*,\s*)?(?:t|q):\s*'((?:[^'\\]|\\.)*)'/g, m;
  while ((m = re.exec(seg))) out.push({ n: m[1] || m[2] || m[3] || '', t: m[4].replace(/\\'/g, "'") });
  return out;
}

function bullets(md, from, to) {
  var a = md.indexOf(from); if (a < 0) return [];
  var b = md.indexOf(to, a); var seg = md.slice(a, b < 0 ? md.length : b);
  var out = [], re = /^-\s+\*\*([^*]+)\*\*/gm, m;
  while ((m = re.exec(seg))) out.push({ t: m[1].replace(/[.,:]\s*$/, '').trim() });
  return out;
}

function numbered(md, from, to) {
  var a = md.indexOf(from); if (a < 0) return [];
  var b = md.indexOf(to, a); var seg = md.slice(a, b < 0 ? md.length : b);
  var out = [], re = /^\d+\.\s+\*\*([^*]+)\*\*/gm, m;
  while ((m = re.exec(seg))) out.push({ t: m[1].replace(/\s*\([^)]*\)\s*$/, '').replace(/[.,:]\s*$/, '').trim() });
  return out;
}

async function build() {
  var md = await readFile('source/README.md');
  var hd = await readFile('source/handoff.dc.html');
  var cu = await readFile('source/curator.dc.html');
  var atoms = [], i = 0;
  var push = function (g, list, extra) {
    list.forEach(function (x) {
      var a = { g: g, id: g[0] + (++i), t: x.t };
      if (KEYS[x.t]) a.key = KEYS[x.t];
      if (g === 'спорные' && x.n) a.key = 'случай ' + x.n + ' · ';
      if (extra) extra(a, x);
      atoms.push(a);
    });
  };

  push('решения', bullets(md, 'Ключевые решения, которые выстояли', '**Программа куратора'));
  push('куратор', bullets(md, 'Правило, из которого следует всё остальное', '## Трек 3'));
  push('инварианты', objs(hd, 'rules: [', 'edges: ['));
  push('спорные', objs(hd, 'edges: [', 'checks: ['));
  push('схема', numbered(md, '## Восемь задач на схему', 'Дополнительно по треку'));
  push('открытые', objs(hd, 'open: [', 'fixes: ['));
  push('перенос', objs(cu, "{ n: 1, q: 'Кто инициирует", '],'));
  Object.keys(WHERE).forEach(function (n) {
    atoms.push({ g: 'экраны', id: 'e' + n, t: n + ' · экран инвентаря', where: WHERE[n] });
  });

  var noKey = atoms.filter(function (a) { return a.g !== 'экраны' && !a.key; });
  await saveFile('canon-atoms.json', JSON.stringify({
    version: 2,
    note: 'сгенерировано canon-atoms.js из source/ — руками не править',
    atoms: atoms,
  }, null, 1));
  log('атомов', atoms.length, '· без ключа', noKey.length, noKey.map(function (a) { return a.g + ': ' + a.t; }).join(' | '));
  return atoms.length;
}
