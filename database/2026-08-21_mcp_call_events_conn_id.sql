-- Псевдоним подключения в сырьё mcp_call (heys/8e2188).
--
-- Зачем. `session_id` считается вместе с идентификатором инстанса функции: на
-- нём держатся нумерация `seq` и уникальность строки. Побочный эффект — при
-- холодном старте в середине реплики куратора обмен разрывается пополам, и
-- вторая часть вызовов в `tasks_mcp_trace` уходит в «вероятные». Замер 18–20.08:
-- подтверждённых 55–65%, то есть треть цепочки каждый раз под вопросом.
--
-- `conn_id` — тот же односторонний срез хэша, но солью служат сутки, а не
-- инстанс: внутри дня он стабилен и собирает обмен целиком, между днями
-- меняется. Сквозного профиля не даёт, идентификаторов людей не содержит —
-- состав таблицы по-прежнему не ПДн.
--
-- Сутки берутся в UTC — это ровно граница taskDay задачника (03:00 МСК),
-- поэтому смена псевдонима совпадает со сменой файла стенограммы и не может
-- разорвать обмен.
--
-- Уникальный индекс (session_id, seq) не трогаем: он и дальше отсекает
-- повторную вставку той же строки при ретрае.

ALTER TABLE mcp_call_events
  ADD COLUMN IF NOT EXISTS conn_id text;

COMMENT ON COLUMN mcp_call_events.conn_id IS
  'Псевдоним подключения с суточной ротацией: собирает обмен, разорванный сменой инстанса. Не ПДн.';

-- Чтение trace идёт окном по времени и уже покрыто mcp_call_events_ts_idx;
-- отдельный индекс нужен для выборки «весь обмен по подключению».
CREATE INDEX IF NOT EXISTS mcp_call_events_conn_ts_idx
  ON mcp_call_events (conn_id, ts DESC)
  WHERE conn_id IS NOT NULL;
