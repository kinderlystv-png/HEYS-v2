-- arg_keys в сырой телеметрии MCP (продолжение heys/8e2188).
--
-- Зачем: по строке mcp_call нельзя было понять, какие поля модель реально
-- передала. Вызов heys_update_meal с copy_meal и вызов с add_items выглядели
-- одинаково, и приёмка «взяла ли модель copy_meal» шла гаданием по числу
-- heys_search_products. 18.08 это стоило четырёх прогонов подряд.
--
-- Что пишем: только ИМЕНА полей верхнего уровня, без значений. Рекурсии нет:
-- у preset_grams вложенные ключи — названия продуктов клиента, они сюда не
-- поднимаются никогда (белый список RECORD_FIELDS в heys-mcp/lib/telemetry.js).
-- Состав строки от этого остаётся не-ПДн, как и был.
--
-- Stdout уже содержит поле с 18.08; колонка нужна, чтобы ключи пережили
-- 3 суток Cloud Logging и попали в tasks_mcp_trace, у которого 180 суток.

ALTER TABLE mcp_call_events
  ADD COLUMN IF NOT EXISTS arg_keys text[];

COMMENT ON COLUMN mcp_call_events.arg_keys IS
  'Имена полей верхнего уровня аргументов вызова, без значений. Максимум 20.';
