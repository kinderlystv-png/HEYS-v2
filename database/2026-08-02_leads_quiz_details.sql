-- 2026-08-02 — уточнения квиза в карточке лида.
--
-- Зачем. Квиз лендинга (`маркетинг/17` §§ 3.1, 3.7) кроме типа срыва собирает
-- три необязательных ответа: частота, барьер и цель. Тип уже хранится в
-- `leads.quiz_segment`, а уточнениям места не было — и версия D обещает
-- человеку «куратор увидит: …», то есть обещание без этой колонки не выполнимо.
--
-- Почему JSONB, а не три колонки: набор уточнений задаётся сценарием квиза и
-- меняется вместе с ним (`17` § 3.1). Отдельные колонки означали бы миграцию на
-- каждый новый вопрос; здесь же чтение идёт целиком, в карточку куратора.
--
-- 152-ФЗ: ответы приходят одним пакетом вместе с контактом и согласием,
-- поштучная отправка до согласия запрещена. Свободного текста в поле нет —
-- только коды вариантов, поэтому новых категорий ПДн колонка не вводит.

ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS quiz_details JSONB;

COMMENT ON COLUMN public.leads.quiz_details IS
  'Необязательные уточнения квиза (частота/барьер/цель) кодами вариантов. Тип срыва — в quiz_segment. Источник: маркетинг/17 § 3.7.';
