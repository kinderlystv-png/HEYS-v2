-- Подсказка, выданная модели на вызове (heys/8e2188).
--
-- Зачем. 21.08 сервер начал подсказывать модели, что круг лишний: повтор того
-- же чтения и серия поисков подряд. Без отметки в телеметрии нельзя ответить на
-- единственный вопрос, ради которого всё делалось, — подсказка меняет поведение
-- или её игнорируют. Считать «стало меньше вызовов» по одному лишь числу
-- вызовов нельзя: трафик по дням разный.
--
-- Значения: NULL — подсказки не было; 'repeat' — тот же вызов с теми же
-- аргументами; 'streak' — второй и далее вызов того же инструмента подряд.
-- CHECK намеренно нет: набор будет пополняться, а телеметрия не имеет права
-- ронять вызов из-за неизвестного значения (тот же принцип, что у status).
--
-- Идентификаторов людей поле не добавляет: это имя правила, не данные вызова.

ALTER TABLE mcp_call_events
  ADD COLUMN IF NOT EXISTS hint text;

COMMENT ON COLUMN mcp_call_events.hint IS
  'Подсказка про лишний круг, выданная модели: repeat | streak | NULL. Имя правила, не данные вызова.';

