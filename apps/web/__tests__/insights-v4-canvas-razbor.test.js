// Покадровый разбор вкладки «Инсайты» — половина зоны reports-insights.
//
// Файл заведён отдельно от `reports-insights-v4-canvas-geometry.test.js`
// намеренно: над зоной работают две сессии, и общий файл гейта был вторым по
// частоте местом, где правка одной уезжала в коммит другой. Пары «Отчётов» и
// пары «Инсайтов» независимы — общий у них только помощник разбора.
//
// Что здесь НЕ живёт: реестр отступлений зоны и проверки общего канона (ярусы,
// карточки, кнопки). Они смотрят обе вкладки сразу и остаются в общем файле.
//
// Метод тот же, что в «Отчётах»: ключ раздела «Разбор кадров» — «<метка кадра>
// · NN», привязка идёт по data-screen-label, а не по классам канваса.
//
// Прежняя причина не трогать эту половину — «зона инлайновая» — относится к
// КАНВАСУ (3836 инлайновых стилей в .dc.html), а не к продукту: у продукта
// инсайтов 1654 обращения к классам против 79 инлайнов, и привязка работает.
import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { compare, coverage, readRazbor, readRules } from './canvas-razbor-helpers.js';

const canvas = fs.readFileSync(
  path.resolve(
    __dirname,
    '../../../docs/ui/handoff-v4/canvas/Переработка дизайна приложения/design_handoff_heys_v4/reports-insights.v4.dc.html',
  ),
  'utf8',
).replace(/\r\n/g, '\n');

const insightsCss = fs.readFileSync(
  path.resolve(__dirname, '../styles/modules/734-ui-v4-insights.css'), 'utf8');

// Отступления инсайтовой половины — поимённо, как в «Отчётах». Строка, попавшая
// сюда, в пары не идёт: пара молча зелёная там, где решение принято осознанно,
// хуже отсутствия пары.
const RAZBOR_EXCEPTIONS = new Map([
  // Счётчик зрелости: строка «вид · шапка зрелости» просит «18 дней данных»
  // 10,5/600 тоном --ac, кадр и строка «счётчик в шапке» дают «18 дней данных
  // из 30» чернилами. Два источника из трёх сходятся на кадре.
  ['Инсайты · 15|*', 'счётчик зрелости: два источника из трёх дают чернила'],
  // Лестница чернил заморожена ступенями 55/45/38/30 — кадр просит 35 % у
  // общего порога и 60 % у прозы «Где они работают», таких ступеней нет.
  ['Инсайты · персональные пороги · 16|color', 'нет ступени 35 %, стоит ближайшая 38 %'],
  ['Инсайты · персональные пороги · 24|color', 'нет ступени 60 %, стоит ближайшая 55 %'],
]);

const HEAD_AND_HERO = [
  [13, '.insights-v4-meta__row', ['align', 'gap']],
  [14, '.insights-v4-meta__title', ['fontWeight', 'fontSize', 'lineHeight', 'color']],
  [15, '.insights-v4-meta__days', ['fontWeight', 'fontSize', 'lineHeight', 'color']],
  [17, '.insights-v4-hero', ['background', 'radius', 'padding', 'marginTop']],
  [19, '.insights-v4-hero__phrase',
    ['fontWeight', 'fontSize', 'lineHeight', 'color', 'marginTop']],
];

// Пары растут вместе с разбором: кадр, закрытый вердиктами, закрепляется здесь,
// иначе «сведено» держится только на том, что кто-то однажды посмотрел глазами.
// Счётчик охвата показал, что гейт брал один кадр из двадцати, — эти два первые,
// добавленные по следам разбора.
const NEW_USER = [
  [6, '.insights-v4-stub__hero', ['background', 'radius', 'padding']],
  [8, '.insights-v4-stub__title', ['fontWeight', 'fontSize', 'lineHeight']],
  [10, '.insights-v4-stub__progress', ['height', 'radius']],
  [12, '.insights-v4-stub__count', ['fontWeight', 'fontSize', 'lineHeight', 'color']],
  [27, '.insights-v4-stub__ladder-text', ['fontWeight', 'fontSize', 'lineHeight']],
];

const THRESHOLDS = [
  [7, '.insights-v4-thresh__count', ['fontWeight', 'fontSize', 'lineHeight', 'color']],
  [14, '.insights-v4-thresh__name', ['fontWeight', 'fontSize', 'lineHeight', 'flex']],
  [15, '.insights-v4-thresh__mine', ['fontWeight', 'fontSize', 'lineHeight', 'color', 'width']],
  // Тон общего порога и прозы «Где они работают» в пары не идёт: кадр просит
  // чернила 35 % и 60 %, а лестница набора заморожена ступенями 55/45/38/30.
  // Код берёт ближайшие — 38 % и 55 %, и это названо в списке отступлений.
  [16, '.insights-v4-thresh__common', ['fontWeight', 'fontSize', 'lineHeight', 'width']],
  [24, '.insights-v4-thresh__where', ['fontWeight', 'fontSize', 'lineHeight']],
];

describe('Инсайты · разбор кадров канваса', () => {
  const razbor = readRazbor(canvas);
  const rules = readRules(insightsCss);

  it('шапка и герой кадра «Инсайты» совпадают с продуктом', () => {
    expect(compare({
      razbor, rules, frame: 'Инсайты', pairs: HEAD_AND_HERO,
    })).toEqual([]);
  });

  it('кадр «новый пользователь» совпадает с продуктом', () => {
    expect(compare({
      razbor, rules, frame: 'Инсайты · новый пользователь', pairs: NEW_USER,
    })).toEqual([]);
  });

  it('кадр «персональные пороги» совпадает с продуктом', () => {
    expect(compare({
      razbor, rules, frame: 'Инсайты · персональные пороги', pairs: THRESHOLDS,
    })).toEqual([]);
  });

  // Охват называется вслух: без этого «сверено гейтом» в обосновании вердикта
  // нельзя проверить иначе как чтением этого файла. Счётчик полезен ровно тем,
  // что его можно сравнить с числом вердиктов, которые на гейт ссылаются, —
  // расхождение между «сколько сверено» и «сколько на это ссылается» иначе
  // видно только владельцу зоны и только вручную.
  //
  // Знаменатель — строки своего кадра, а не всего канваса: отчётные кадры того
  // же файла сверяет reports-insights-v4-canvas-geometry.test.js, и класть их
  // сюда значило бы называть чужую работу своим непокрытием.
  it('гейт называет свой охват', () => {
    const { perFrame } = coverage({ razbor });
    const mine = perFrame.filter((f) => f.frame === 'Инсайты');
    expect(mine).toHaveLength(1);
    const [f] = mine;
    // Границу половины берём списком кадров, а не именем: пять инсайтовых
    // кадров названы без слова «Инсайты» («Раскрывашка · …», «Стоит внимания ·
    // …», «Ярус Питание · …»), и отбор по имени разъезжается — на этом сегодня
    // дважды разошёлся реестр отступлений соседнего гейта.
    const REPORTS = [
      'Визуал v4 · Отчёты', 'Разбор Score', 'Отчёты · мало данных',
      'Отчёты · нулевая строка матрицы', 'Отчёты · нет веса',
      'Неделя к неделе · одна закрытая',
    ];
    const insightFrames = perFrame.filter((x) => !REPORTS.includes(x.frame));
    const untouched = insightFrames.filter((x) => !x.covered).map((x) => x.frame);
    console.info(
      `[инсайты] сверено ${f.covered} из ${f.rows} строк разбора кадра «${f.frame}» `
      + `(${((f.covered / f.rows) * 100).toFixed(1)} %). Инсайтовых кадров в канвасе `
      + `${insightFrames.length}, парами этот гейт не берёт ${untouched.length}: `
      + `${untouched.slice(0, 3).join(' · ')}…; отчётные кадры сверяет `
      + 'reports-insights-v4-canvas-geometry',
    );
    expect(f.covered).toBeGreaterThan(0);
  });

  it('отступления инсайтовой половины названы и не разрастаются молча', () => {
    expect(RAZBOR_EXCEPTIONS.size).toBe(3);
  });

  // Реестр отступлений разделён так же, как гейт: ключи кадров «Инсайты · NN»
  // живут здесь, отчётные — в reports-insights-v4-canvas-geometry.test.js.
  // Именованные строки контракта («роли цвета», «карточка · планер») остались
  // общими: они описывают обе вкладки, и присваивать их одной половине неверно.
  //
  // Ярус «Каскад», элементы 25–51, — двадцать семь записей с одной причиной:
  // их рисует не инсайтовый CSS, а общий 740-cascade-card.css, пре-v4 компонент
  // чужой зоны. Семейства insights-v4-cascade не существует вовсе, поэтому
  // сверять пары не с чем: это не расхождение чисел, а отсутствие своей
  // реализации. Двадцать восьмая — строка действия героя: контракт описывает
  // строки высотой 34 с разделителем, кадр — отдельные карточки на --bg.
  const MY_FRAMES = [
    'Инсайты',
    'Раскрывашка · ',
    'Стоит внимания · ',
    'Ярус Питание · ',
  ];

  const DEVIATIONS = [
    'Инсайты · 25',
    'Инсайты · 26',
    'Инсайты · 27',
    'Инсайты · 28',
    'Инсайты · 29',
    'Инсайты · 30',
    'Инсайты · 31',
    'Инсайты · 32',
    'Инсайты · 33',
    'Инсайты · 34',
    'Инсайты · 35',
    'Инсайты · 36',
    'Инсайты · 37',
    'Инсайты · 38',
    'Инсайты · 39',
    'Инсайты · 40',
    'Инсайты · 41',
    'Инсайты · 42',
    'Инсайты · 43',
    'Инсайты · 44',
    'Инсайты · 45',
    'Инсайты · 46',
    'Инсайты · 47',
    'Инсайты · 48',
    'Инсайты · 49',
    'Инсайты · 50',
    'Инсайты · 51',
    'Инсайты · 21',
    // Кадр «Инсайты · подробно», элементы 06–10: блок прогноза веса не переведён
    // на v4 — его рисует WeightPrediction классами insights-weight__* из
    // 720-predictive-insights.css. Устройство другое («Сейчас · значение ·
    // стрелка» против «Через неделю · вес · темп»), а фразы «такими темпами
    // −1,8 кг в месяц» в коде нет вовсе, хотя строка «один показатель — одна
    // роль» отводит эту экстраполяцию только сюда.
    'Инсайты · подробно · 06',
    'Инсайты · подробно · 07',
    'Инсайты · подробно · 08',
    'Инсайты · подробно · 09',
    'Инсайты · подробно · 10',
    // Кадр «Инсайты · ярус Питание», элемент 14: кадр рисует границу окна
    // приёмов («до 20:30») акцентом, а продукт показывает время последнего
    // приёма тем же классом, что и первое. Расхождение смысла, а не
    // оформления: «до какого времени есть» и «когда ели в последний раз» —
    // разные величины, одним классом их не показать. Кегль приведён к кадру,
    // остальное уходит вопросом дизайнеру.
    'Инсайты · ярус Питание · 14',
    // Кадры «Стоит внимания»: текст сигнала и отступ строки меты. Класс
    // .insights-v4-attention__text один на оба состояния карточки — обычное и
    // «всё хорошо»; кадры просят 600 против 500 в коде, а развести их значит
    // завести второй вид карточки, чего строка «карточка · сигнал» не просит.
    // Отступ меты 6 против 10 и 9 — те же 4 px в двух кадрах одного элемента.
    'Стоит внимания · голос куратора · 06',
    'Стоит внимания · голос куратора · 07',
    'Стоит внимания · голос куратора · 08',
    'Стоит внимания · панель Ещё · 07',
    'Стоит внимания · панель Ещё · 08',
  ];

  it('отступления инсайтовых кадров названы поимённо', () => {
    const verdicts = JSON.parse(fs.readFileSync(
      path.resolve(__dirname, '../../../docs/ui/verdicts/reports-insights.json'), 'utf8'));
    const notEqual = Object.entries(verdicts.rows)
      .filter(([, row]) => row.v === '≠')
      .map(([key]) => key)
      // Граница — список кадров, а не форма ключа. Дважды подряд имя оказалось
      // не тем признаком: сперва фильтр «Инсайты · NN» не поймал подкадры
      // («Инсайты · подробно · 06»), потом префикс «Инсайты · » не поймал пять
      // кадров, названных без этого слова, — раскрывашки, «Стоит внимания» и
      // ярус Питание. Шестьдесят строк не проверял никто.
      //
      // Признак принадлежности — кто рисует: все пять собираются в
      // apps/web/insights/ (pi_ui_dashboard.js, pi_early_warning.js,
      // pi_ui_meal_rec_card.js), из отчётного CSS не приходит ни одна.
      // Проверено по коду, а не по метке.
      //
      // Цена решения названа честно: список пополняется руками при каждом новом
      // кадре пакета. Регулярка этого не требовала, но и не работала — оба раза
      // молчала в чужую сторону, краснел чужой гейт на чужой работе.
      .filter((key) => MY_FRAMES.some((frame) => key.startsWith(frame)));

    expect([...new Set(DEVIATIONS)]).toHaveLength(DEVIATIONS.length);

    // Стороны названы порознь: починки у них разные. «Нет в реестре» —
    // отступление появилось молча, его надо назвать причиной. «Нет в снимке» —
    // либо вердикт не поставлен, либо расхождение уже сведено.
    const missingInRegistry = notEqual.filter((key) => !DEVIATIONS.includes(key));
    const missingInSnapshot = DEVIATIONS.filter((key) => !notEqual.includes(key));
    expect(missingInRegistry, 'в снимке есть «≠» инсайтовых кадров, которых нет '
      + 'в этом реестре — назовите отступление здесь или сведите экран').toEqual([]);
    expect(missingInSnapshot, 'в реестре есть ключи, у которых в снимке нет «≠» — '
      + 'поставьте вердикт или уберите ключ отсюда').toEqual([]);
  });
});
