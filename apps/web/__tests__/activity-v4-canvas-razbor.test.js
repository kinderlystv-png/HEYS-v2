// Текстовые копии кадров «Актива» против продукта.
//
// Тринадцать кадров этой зоны канвас дублирует строкой «<метка> · текст» — полной
// копией того, что человек видит на экране. Восемь из них закрыты вердиктом `=`
// с обоснованием «копия сверена пословно», и до сих пор это была именно
// пословная сверка глазами: машинной проверки у зоны не было, в отличие от
// десятка соседних зон с их `*-canvas-razbor.test.js`.
//
// Разница с `activity-v4-canvas-geometry.test.js`: тот сверяет классы канваса с
// классами продукта и о словах ничего не знает. Здесь наоборот — только слова.
//
// Сверка двусторонняя, и в этом весь смысл. Фраза обязана найтись и в копии
// кадра, и в исходнике: пропадёт из продукта — упадёт вторая половина, перепишет
// дизайнер копию — упадёт первая. Односторонняя проверка «строка есть в коде»
// пережила бы переписанный кадр молча, а это ровно тот случай, ради которого
// заведён снимок вердиктов.
//
// Фразы берутся из обоснований самих вердиктов: список — это то, что было
// сверено глазами при сведении экрана, теперь закреплённое.
import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

const CANVAS = path.resolve(
  __dirname,
  '../../../docs/ui/handoff-v4/canvas/Переработка дизайна приложения/design_handoff_heys_v4/tab-activity.v4.dc.html',
);

// Продуктовые исходники зоны. Программа и предложение куратора живут в силовом
// модуле, зарядка и шаги — в своих: одна вкладка собрана из нескольких файлов,
// поэтому фраза ищется по всем сразу.
const SOURCES = [
  '../heys_day_activity_v1.js',
  '../heys_day_tab_impl_v1.js',
  '../heys_day_trainings_v1.js',
  '../heys_steps_v1.js',
  '../strength/heys_strength_proposal_ui_v1.js',
  '../strength/heys_strength_superset_ui_v1.js',
];

/**
 * Фразы кадра. Берутся короткими фрагментами, а не целыми предложениями:
 * «Куратор поправил сегодняшнюю тренировку» в коде склеено из имени и хвоста
 * (`who + ' поправил сегодняшнюю тренировку'`), и поиск целой фразы дал бы
 * ложное «в продукте этого нет».
 */
const FRAMES = [
  ['Актив · разбор цели · текст', [
    'от неё считается цель',
    'в затратах есть, в цели нет',
    'Дефицит по договорённости',
    'Компенсация долга',
  ]],
  ['Актив · новый человек · текст', [
    'от затрат без термического эффекта',
    'не отмечено',
  ]],
  ['Актив · шаги оценены · текст', [
    'поставьте факт ползунком',
  ]],
  ['Актив · план назначен · текст', [
    'В расход не идёт, пока не начнёте',
  ]],
  ['Актив · правка куратора · текст', [
    'поправил сегодняшнюю тренировку',
    'Оставить прежнюю',
  ]],
  ['Актив · день отдыха · текст', [
    'день отдыха',
  ]],
  ['Рабочие веса · нечего сравнивать · текст', [
    'рано сравнивать',
    'нет общих упражнений',
  ]],
  ['Актив · тренировка идёт · текст', [
    'силовая идёт',
    'Пока тренировка идёт',
  ]],
  ['Актив · нагрузка предупреждает · текст', [
    'Сегодня лучше жать, чем тянуть',
    'Взять день жимов',
    'Основная группа берёт полный вес',
  ]],
  ['Актив · нагрузка слои · текст', [
    'Как меняется',
    'Вклад этой сессии',
    'Вердикт сессии',
  ]],
  // Ряд «Минуты по зонам» — два кадра-состояния сборки 71, сведены по ответу
  // сборки 72: ряд живёт внутри раскрытой карточки тренировки. Второй кадр
  // нужен затем, чтобы условие «названные подписи не получают» было
  // проверяемым: слова пометки в нём нет, и это проверяет тест ниже.
  ['Зоны · оценены по типу · текст', [
    'Минуты по зонам',
    'Зона 2 · лёгкая',
    'Зона 3 · средняя',
    'зоны оценены по типу тренировки',
  ]],
  ['Зоны · названы человеком · текст', [
    'Минуты по зонам',
    'Зона 4 · тяжёлая',
  ]],
];

describe('«Актив» · текстовые копии кадров', () => {
  const canvas = fs.readFileSync(CANVAS, 'utf8');
  const sources = SOURCES.map((rel) => fs.readFileSync(path.resolve(__dirname, rel), 'utf8')).join('\n');

  /** Копия кадра из канваса: значение строки «<метка> · текст». */
  const copyOf = (frame) => {
    // Поиск подстрокой, а не регуляркой: метки кадров содержат «·» и пробелы,
    // экранировать нечего, а собранная регулярка — лишний источник ошибок.
    const head = `<b>${frame}</b><span data-v="`;
    const at = canvas.indexOf(head);
    if (at < 0) return null;
    const from = at + head.length;
    const end = canvas.indexOf('"', from);
    return end < 0 ? null : canvas.slice(from, end);
  };

  it.each(FRAMES)('кадр «%s» и продукт говорят одними словами', (frame, phrases) => {
    const copy = copyOf(frame);
    expect(copy, `строки «${frame}» нет в канвасе`).not.toBeNull();
    const missing = [];
    for (const phrase of phrases) {
      if (!copy.includes(phrase)) missing.push(`${phrase} — нет в копии кадра`);
      if (!sources.includes(phrase)) missing.push(`${phrase} — нет в продукте`);
    }
    expect(missing).toEqual([]);
  });

  // Два кадра этой зоны закрыты вердиктом `≠`, и расхождение там названо: кадр
  // «день собран» рисует программу компактной строкой списка, а продукт —
  // карточкой; кадр «журнал подходов» описывает завершённую тренировку, продукт
  // показывает идущую. Проверка держит сам факт расхождения: пропадут эти строки
  // из канваса — вердикты станут ссылаться в пустоту, и об этом надо узнать.
  it.each([
    'Актив · день собран · текст',
    'Тренировки · журнал подходов · текст',
  ])('кадр «%s» на месте — его вердикт `≠` ссылается на живую строку', (frame) => {
    expect(copyOf(frame), `строки «${frame}» нет в канвасе`).not.toBeNull();
  });

  // Условие пометки проверяемо только парой кадров: в «названы человеком» её
  // нет, и отсутствие проверяется так же строго, как наличие.
  it('кадр «названы человеком» пометки не несёт — иначе условие ничем не держится', () => {
    expect(copyOf('Зоны · названы человеком · текст')).not.toContain('зоны оценены по типу');
    expect(copyOf('Зоны · оценены по типу · текст')).toContain('зоны оценены по типу');
  });

  // Охват назван числом: пятнадцать текстовых копий в канвасе, двенадцать
  // сверяются пословно, две стоят расхождением. Пятнадцатая — «Календарь
  // зарядки · текст»: её слова («28 дней», «Месяц», подписи легенды) уже держит
  // `activity-zero-and-calendar-grid.test.js`, второй раз их сверять нечем.
  it('все текстовые копии кадров учтены', () => {
    const all = [...canvas.matchAll(/<b>([^<]*· текст)<\/b>/g)].map((m) => m[1]);
    expect(all).toHaveLength(15);
    const known = new Set([
      ...FRAMES.map(([frame]) => frame),
      'Актив · день собран · текст',
      'Тренировки · журнал подходов · текст',
      'Зоны · оценены по типу · текст',
      'Зоны · названы человеком · текст',
      'Календарь зарядки · текст',
    ]);
    expect(all.filter((frame) => !known.has(frame))).toEqual([]);
  });
});
