// Анкета и регистрация против разбора кадров канваса — сверка по исходнику,
// а не по CSS.
//
// Геометрия этих двух зон живёт инлайном в JS: в `heys_trial_intake_v1.js`
// 82 блока `style: {}` и ни одного `className`, шаги профиля — тем же приёмом.
// Сверка «класс канваса → правило продукта», которая работает во «Входе»,
// «Советах» и «Дате», здесь не находит вообще ничего, поэтому числа читаются из
// исходника.
//
// Спорные места решает именованная строка своей зоны: разбор кадров обеих зон
// расходится с их же контрактом чаще, чем с кодом.
import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

const WEB = path.resolve(__dirname, '..');
const INTAKE = fs.readFileSync(path.join(WEB, 'heys_trial_intake_v1.js'), 'utf8');
const PROFILE = fs.readFileSync(path.join(WEB, 'heys_profile_step_v1.js'), 'utf8');

describe('«Анкета» · разбор кадров против исходника', () => {
  // Строка «вид блока предупреждения»: «фон --c1, радиус 18, поля 14/16 px,
  // кегль 12 px/1,6… квадрат 22 px радиусом 6». Кадр «Анкета · шаг 1» рисует
  // блок тинтом с полями 15 и кеглем 11,5/1,55, а первую отметку радиусом 7 —
  // контракт старше кадра, и код следует контракту.
  it('блок предупреждения — первая поверхность, поля 14/16, кегль 12/1,6', () => {
    const block = INTAKE.slice(INTAKE.indexOf("id: 'intake-warning-text'"));
    const head = block.slice(0, block.indexOf('},'));
    expect(head).toMatch(/padding: '14px 16px'/);
    expect(head).toMatch(/borderRadius: 18/);
    expect(head).toMatch(/background: SURFACE_1/);
    expect(head).toMatch(/fontSize: 12/);
    expect(head).toMatch(/lineHeight: 1\.6/);
    // Своя область прокрутки: без неё четыре абзаца выталкивают отметку с экрана.
    expect(head).toMatch(/maxHeight: 186/);
    expect(head).toMatch(/overflowY: 'auto'/);
  });

  it('отметка согласия — квадрат 22 радиусом 6, одна форма на обе', () => {
    expect(INTAKE).toMatch(/width: 22, height: 22[\s\S]{0,120}borderRadius: 6/);
    // Кадр рисует две отметки подряд разными (радиус 7 с --c1 и радиус 6 с
    // --bg); в коде форма одна — второй язык отметки ради одного кадра не
    // заводим, строка контракта называет только радиус 6.
    expect(INTAKE).not.toMatch(/borderRadius: 7,[\s\S]{0,80}checked \? ACCENT_FILL/);
  });

  // Строка «вид · кегли шага»: заголовок 22/1,2/700, подзаголовок 12,5/1,55/500.
  it('кегли шага анкеты — по своей строке контракта', () => {
    expect(INTAKE).toMatch(/fontSize: 22, fontWeight: 700, lineHeight: 1\.2/);
  });
});

describe('«Регистрация» · разбор кадров против исходника', () => {
  // Строка «вид шага»: «заголовок 20 px/700 чернилами с отступом сверху 6».
  it('заголовок шага — 20/700 с отступом сверху 6', () => {
    expect(PROFILE).toMatch(/fontSize: 20, fontWeight: 700, color: '#201e1d', marginTop: 6/);
  });

  // Кадр «Регистрация · рост и вес», элемент 09: карточка колеса на первой
  // поверхности радиусом 18 с полями 13/0/14 и текстом по центру.
  it('карточка колеса — первая поверхность, радиус 18, поля 13/0/14', () => {
    expect(PROFILE).toMatch(/background: '#f7efe2', borderRadius: 18, padding: '13px 0 14px'/);
  });

  // Тот же кадр, элементы 17 и 20: карточки ИМТ на второй поверхности радиусом
  // 16 с полями 12/14, число 18/700 чернилами, значение по базовой линии через 6.
  it('карточки ИМТ — вторая поверхность, радиус 16, поля 12/14', () => {
    expect(PROFILE).toMatch(/background: '#efe3cf', borderRadius: 16, padding: '12px 14px'/);
    expect(PROFILE).toMatch(/alignItems: 'baseline', gap: 6, marginTop: 6/);
    expect(PROFILE).toMatch(/fontSize: 18, fontWeight: 700, color: '#201e1d'/);
  });

  // Расхождение, которое не чинится вслепую: строка «вид шага» просит у карточек
  // внутри шага зазор 8, а контейнер шага стоит на `gap-3` (12 px), и разницу
  // догоняют отдельные marginTop у детей — их в файле тридцать пять. Проверка
  // фиксирует текущее состояние, чтобы правка зазора не прошла молча: менять
  // его нужно вместе с пересмотром этих отступов и глазами на живом экране.
  //
  // Долг уменьшился 2 сентября: блок даты рождения перешёл с `gap-3` на
  // семантический класс `profile-personal-birth` с явным marginTop у карточки
  // колеса (8px) вместо утилитарного зазора — дети не наезжают друг на друга,
  // интервал расставлен сознательно. Осталось одно место.
  it('зазор шага пока 12, а не 8 из строки «вид шага»', () => {
    expect(PROFILE.match(/className: 'flex flex-col gap-3'/g)).toHaveLength(1);
  });
});
