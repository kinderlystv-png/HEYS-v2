// Регистрация против контракта своего канваса.
//
// Особенность зоны: шаги профиля и экран согласий написаны инлайновыми стилями,
// а не классами. Пары «класс кадра → класс продукта» здесь не построить, и по
// правилу сведения такой тест заводят только когда геометрия реально
// разъезжается. Она разъезжалась: на всех четырёх шагах ярусы набирались 12 px
// трекингом .1em вместо 10 и .16em, карточки шли радиусом 12 с полями 16/12
// вместо 14 и 12/14, подписи 14 px вместо 12, сноски 12 px вместо 10,5.
//
// Поэтому проверка держит не всю геометрию, а те решения контракта, которые
// продукт нарушал, и те, которые он соблюдает вопреки кадру. Второе не менее
// важно: карточку итогов я едва не развела на три вида, идя по кадрам.
import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

const read = (rel) => fs.readFileSync(path.resolve(__dirname, rel), 'utf8');
const profile = read('../heys_profile_step_v1.js');
const consents = read('../heys_consents_v1.js');
const stepModal = read('../heys_step_modal_v1.js');
const userTab = read('../heys_user_tab_impl_v1.js');
const loginCss = read('../styles/modules/733-ui-v4-login-theme.css');
const pwaCss = read('../styles/modules/500-pwa-and-offline.css');

describe('регистрация v4: решения контракта', () => {
  // Три следующих шага сохраняют пояснения из общего контракта. Первый кадр
  // «Персональные данные» пояснение не рисует: frame-level источник имеет
  // приоритет, а конфликт с общей строкой зафиксирован дизайнеру.
  const SUBTITLES = [
    'Вес будете уточнять каждое утро, здесь только точка отсчёта',
    'Цель можно поменять в любой момент',
    'По этим двум числам считается окно приёмов',
  ];

  it.each(SUBTITLES)('пояснение «%s» на месте', (text) => {
    expect(profile).toContain(text);
  });

  it('три оставшихся пояснения набраны одинаково: 12/500 через 9', () => {
    // Стояли вразнобой — три через 8, у «роста и веса» отступа не было вовсе.
    const shape = /fontSize: 12, fontWeight: 500, color: 'rgba\(0,0,0,\.55\)', lineHeight: 1\.5, marginTop: 9/g;
    expect((profile.match(shape) || []).length).toBe(3);
    // Конфиг шага сохраняет hint для недневной оболочки/доступности, но
    // компонент кадра не дублирует его в содержимом.
    expect((profile.match(/Имя увидит только ваш куратор/g) || []).length).toBe(1);
  });

  // Строка «вид карточки итогов»: фон --c2, радиус 20, поля 14/16, строки
  // 12 px/600 шагом 11. Три кадра концов рисуют три разные карточки — контракт
  // ставит одну намеренно: концы различаются смыслом, а не оформлением.
  it('карточка итогов одна на три конца и следует контракту, а не кадрам', () => {
    expect(profile).toMatch(/background: '#efe3cf',\s*\n?\s*borderRadius: 20,\s*\n?\s*padding: '14px 16px'/);
    expect((profile.match(/cardShell\(/g) || []).length).toBe(3);
  });

  // Строка «цель касания»: минимум 44 pt держат строка, чип и кнопка. Кадры
  // рисуют 40 в пяти местах — контракт старше.
  it('кнопка отказа в документе держит 44, а не 40 из кадра', () => {
    expect(loginCss).toMatch(/\.consent-fulltext__decline \{[^}]*min-height: 44px/s);
  });

  // Строка «вид прогресса чтения»: дорожка 3 px радиусом 999 фоном чернил 9 %.
  // Радиуса не было вовсе, тон стоял 7 %.
  it('дорожка чтения документа — радиус 999 и чернила 9 %', () => {
    expect(loginCss).toMatch(/\.consent-fulltext__progress-track \{[^}]*border-radius: 999px/s);
    expect(loginCss).toMatch(/\.consent-fulltext__progress-track \{[^}]*rgba\(0, 0, 0, 0\.09\)/s);
  });

  // Тумблер профиля: кадр «Профиль · низ» даёт 40×24 с ручкой 18. Заодно он
  // перестал знать про набор — роль с именем набора в модуле незаконна.
  it('тумблер профиля 40×24 с ручкой 18 и общими ролями', () => {
    expect(pwaCss).toMatch(/\.profile-v4-toggle \{[^}]*width: 40px;[^}]*height: 24px/s);
    expect(pwaCss).toMatch(/\.profile-v4-toggle__thumb \{[^}]*width: 18px/s);
    expect(pwaCss).not.toMatch(/\.profile-v4-toggle[^{]*\{[^}]*--v4-sand-/s);
  });

  // Строка «желаемый вес», решение 31 августа: тревожный тон --ac2 только у
  // НЕДОСТАТКА веса; «избыток» идёт приглушёнными чернилами, и кадр «рост и
  // вес», который красит им и «избыток», перекрашивается. Довод строки: на
  // третьем шаге регистрации человек ещё не вошёл в продукт, и говорить ему
  // тоном тревоги, что с ним что-то не так, — не то, ради чего шаг стоит.
  // До 31 августа гейт сторожил здесь обратное правило — «предупреждать во
  // всех случаях, кроме нормы».
  it('тоном тревоги набран только недостаток веса', () => {
    expect(profile).toMatch(/bmiWord === 'недостаток' \? '#a1471c' : 'rgba\(0,0,0,\.45\)'/);
    expect(profile).toMatch(/goalBmi > 0 && goalBmi < 18\.5[\s\S]{0,80}\? 'не строим'/);
  });

  // Экран согласий: код следует общей строке «неактивная кнопка» (500 тоном
  // 55 %). Кадр после пересъёмки 31 августа рисует 600 и 56 %; конфликт внутри
  // одного канваса остаётся именованным расхождением, а не молчаливой заменой
  // правила доступности кадром.
  it('причина под неактивной кнопкой набрана по контракту, а не по кадру', () => {
    expect(consents).toMatch(/font: '500 11\.5px\/1\.45 Figtree[^']*',\s*\n?\s*color: 'rgba\(0,0,0,\.55\)'/);
  });

  it('обновлённые строки данных используют роль чернил 56 %, не локальные литералы', () => {
    const role = "const INK_DATA = 'var(--v4-ink-data, rgba(0,0,0,.56))';";
    expect(profile).toContain(role);
    expect(consents).toContain(role);
    expect(stepModal).toContain(role);
    expect(userTab).toContain(role);

    const nearby = (source, text, before = 320) => {
      const at = source.indexOf(text);
      expect(at, text).toBeGreaterThan(-1);
      expect(source.slice(Math.max(0, at - before), at), text).toContain('color: INK_DATA');
    };

    nearby(profile, 'Формула основного обмена у мужчин и женщин разная.');
    nearby(profile, 'Куратор обращается к вам по имени, поэтому оно должно читаться.');
    nearby(profile, 'Программа рассчитана на взрослых, и документы подписывает совершеннолетний.');
    nearby(profile, 'При росте ${height} см нижняя граница нормы');
    nearby(profile, 'Волна задаёт, сколько после приёма пищи держится подъём инсулина');
    nearby(profile, 'До этого дня приложение можно не открывать — считать ещё нечего.');
    nearby(profile, 'Норма калорий считается каждый день по факту');
    nearby(consents, 'Введите код доступа — он заменяет собственноручную подпись.');
    nearby(consents, 'Необязательное отмечается тапом и меняется в настройках');
    nearby(consents, 'Копия подписи хранится в профиле — её видно в настройках');
    nearby(stepModal, 'Попытка ${profileRetryAttempt} · следующая через');
    expect(userTab).toMatch(/className: 'profile-v4__subtier-title',[\s\S]{0,100}color: INK_DATA/);
  });

  it('кадр подписи показывает пояснение, а итог не повторяет заголовок ввода', () => {
    expect(consents).toMatch(/!signSuccess && React\.createElement\(React\.Fragment[\s\S]*Введите код доступа — он заменяет собственноручную подпись\./);
    expect(consents).toContain('Копия подписи хранится в профиле — её видно в настройках');
  });

  // Цвета снятой системы на шагах профиля: белый фон невыбранной цели, серые
  // рамки полей и --color-gray-500 у подсказок.
  it('на сведённых шагах не осталось цветов снятой системы', () => {
    // Комментарии не в счёт: в них эти имена названы как то, что убрано.
    const code = profile.replace(/\/\/[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');
    // Белый фон невыбранной цели, серая рамка поля даты, --color-gray-500 у
    // подсказок темпа и активности — всё это стояло на сведённых шагах и ушло.
    for (const dead of ['border-gray-300', '#e5e7eb', 'color-gray-500']) {
      expect(code, dead).not.toContain(dead);
    }
    // Два места вне кадров этой зоны остаются: кнопка удаления фото профиля
    // (bg-gray-100/text-gray-500) и вёрстка внутри строкового шаблона. Кадров
    // на них в registration нет, и чинить их по догадке нельзя — счёт заморожен,
    // чтобы новые не прибавлялись молча.
    expect((code.match(/text-gray-500/g) || []).length).toBe(2);
  });
});
