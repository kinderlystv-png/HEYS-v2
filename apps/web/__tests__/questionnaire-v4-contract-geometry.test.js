// Анкета против контракта своего канваса.
//
// Особенность зоны: её кадры расходятся с её же контрактом почти везде, а код
// следует контракту. Плашка доступа, карточка вопроса, поле ввода, подпись в
// сводке, круг и заголовок финала — во всех этих местах кадр рисует одно, а
// именованная строка говорит другое, и правым каждый раз оказывался код.
//
// Поэтому тест держит в первую очередь то, что легко «починить» по кадру и
// сломать: за день я дважды была в шаге от такой правки. Во вторую — то, что
// действительно исправлено, включая слова.
import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

const SRC = fs.readFileSync(path.resolve(__dirname, '../heys_trial_intake_v1.js'), 'utf8');

describe('анкета v4: решения контракта', () => {
  // Строка «вид карточки вопроса»: карточка --c1 радиусом 18 с полями 14/16,
  // поле внутри — фон --bg, радиус 14, высота не меньше 44. Кадры дают радиус
  // 16 и поля 12–13/15 у обоих.
  it('карточка вопроса и поле следуют контракту, а не кадрам', () => {
    expect(SRC).toMatch(/background: SURFACE_1, borderRadius: 18, padding: '14px 16px'/);
    expect(SRC).toMatch(/borderRadius: 14, minHeight: 44, padding: '12px 14px'/);
  });

  // Строка «вид плашки доступа»: фон --tint, поля 13/15, текст 11,5/500 тоном
  // чернил 60 %. Кадр шага 2 ставит её на --c1 с полями 14/15.
  it('плашка доступа стоит на --tint с полями 13/15', () => {
    expect(SRC).toMatch(/padding: '13px 15px', borderRadius: 18, background: TINT/);
  });

  // Строка «вид финала»: круг 60 с галочкой 28, заголовок 20/700 через 18.
  // Кадр рисует круг 46 радиусом 16 и заголовок 22.
  it('финал — круг 60 и заголовок 20, как в контракте', () => {
    expect(SRC).toMatch(/width: 60, height: 60, borderRadius: 999/);
    expect(SRC).toMatch(/fontSize: 20, fontWeight: 700, lineHeight: 1\.2, letterSpacing: '-\.02em'/);
  });

  // Строка «вид сводки»: подпись вопроса 9,5/700 прописными тоном чернил 40 %.
  // Кадр набирает 600 и 55 %.
  it('подпись в сводке — 700 тоном чернил 40 %', () => {
    expect(SRC).toMatch(/fontSize: 9\.5, fontWeight: 700, lineHeight: 1, letterSpacing: '\.14em'[^}]*color: INK_40/);
  });

  // Строки «одно правило» и «отправка»: причина — строка над кнопкой, а не
  // плашка, и текст ровно «Поставьте галочку выше». Кадр рисует плашку --tint с
  // хвостом «, чтобы отправить анкету». На этом я один раз ошиблась в вердикте.
  it('причина недоступности на шаге — строка, а не плашка', () => {
    // Причин две, и они разные по устройству: на шаге строка без подложки, в
    // сводке плашка --tint («Вернитесь к шагу N и подтвердите предупреждение»),
    // и кадр сводки этой плашке как раз соответствует. Оба элемента несут один
    // id, поэтому окно берётся от текста шага, а не от id.
    const at = SRC.indexOf("'Поставьте галочку выше'");
    expect(at).toBeGreaterThan(-1);
    const block = SRC.slice(at - 400, at + 60);
    expect(block).not.toMatch(/background:\s*TINT/);
    expect(block).not.toContain('чтобы отправить анкету');
    expect(block).toMatch(/textAlign: 'center', color: INK_55/);
  });

  // Строка «слова на экране» запрещает обращения от лица команды. Кадр с ней
  // согласен — здесь правым был не код.
  it('в подводках шагов нет обращения от лица команды', () => {
    // Без комментариев: в них прежняя формулировка названа как убранная.
    const code = SRC.replace(/\/\/[^\n]*/g, '');
    expect(code).toContain('Нужен реальный контекст, а не идеальная неделя.');
    expect(code).not.toContain('Нам нужен реальный контекст');
    expect(code).not.toMatch(/subtitle: '[^']*расскажите нам/i);
  });

  // Копия по кадру: «расходится копия в коде — верна строка».
  it('подводка целей набрана порядком слов кадра', () => {
    expect(SRC).toContain('своими словами — правильных ответов здесь нет.');
  });

  // Метка непройденного шага берёт фон карточки: кружок сливается, остаётся
  // цифра. Роль --v4-card объявлена во всех четырёх наборах, поэтому слияние
  // работает и в синих темах — проверено замером computed.
  it('метка непройденного шага сливается с карточкой', () => {
    expect(SRC).toMatch(/background: done \? OK_BG : currentRow \? ACCENT_FILL : SURFACE_1/);
  });

  // Роль с именем набора в модуле незаконна: в синих темах она держит песочное
  // значение. Замер: --v4-act в синей теме даёт #2e7cc0, --v4-sand-act — #c67139.
  it('модуль не знает, что палитра песочная', () => {
    expect(SRC.replace(/\/\/[^\n]*/g, '')).not.toContain('--v4-sand-');
  });

  // --v4-sand-tint это #f3e0d2 (тон капсулы прошлого дня), а подложка-подсказка
  // --v4-tint — #f6e6dd. Тона похожи, подмена не бросается в глаза.
  it('подложка-подсказка взята из своей роли, а не из тона прошлого дня', () => {
    expect(SRC).toContain("const TINT = 'var(--v4-tint, #f6e6dd)'");
  });
});
