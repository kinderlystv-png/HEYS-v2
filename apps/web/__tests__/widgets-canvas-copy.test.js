// Копия кадров Главной против раздела канваса «Текст кадров дословно».
// Раздел даёт слова каждого кадра по порядку сверху вниз; здесь проверяется,
// что слова, которые продукт обязан произнести сам, в коде есть.
//
// Почему отдельно от геометрии: расхождение в словах не ловит ни один гейт по
// числам, а человек читает именно слова. Так нашлось «Одиннадцать плиток» при
// тринадцати в составе и «сб — самый слабый день недели» вместо «Суббота».
import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

const WEB = path.resolve(__dirname, '..');
const CANVAS = path.resolve(
  WEB,
  '../../docs/ui/handoff-v4/canvas/Переработка дизайна приложения/design_handoff_heys_v4/home-widgets.v4.dc.html',
);
const SOURCES = [
  'heys_widgets_ui_v1.js',
  'heys_widgets_variants_v4.js',
  'heys_widgets_core_v1.js',
  'heys_widgets_registry_v1.js',
  'heys_widgets_insulin_wave_v4.js',
  'heys_widgets_weight_dynamics_v4.js',
  'widgets/widget_data.js'
];

// Строки «текст» раздела: метка кадра → слова по порядку.
function readFrameCopy(source) {
  const frames = new Map();
  const re = /<div class="spec"[^>]*><b>([^<]+) · текст<\/b><span data-v="([^"]*)"/g;
  let m;
  while ((m = re.exec(source))) frames.set(m[1], m[2].split(' › '));
  return frames;
}

// Число в кадре — демо-данные, в коде на его месте подстановка. Сравниваем
// скелет: цифры и `${...}` схлопываются в один знак вместе с пробелами вокруг.
function skeleton(text) {
  return text
    .replace(/\$\{[^}]*\}/g, '#')
    .replace(/[\d ]+(?:[  ,.:]\d+)*/g, '#')
    .replace(/\s*#\s*/g, '#')
    .replace(/#+/g, '#')
    .replace(/\s+/g, ' ')
    .trim();
}

// Слово продукта: есть кириллица и строка не начинается с числа.
const isWord = (t) => /[А-Яа-яЁё]{3,}/.test(t) && !/^\d/.test(t);

// Слова, которые произносит не продукт, а данные: имена продуктов из каталога,
// значения движка и демо-подписи кадра. Каждое названо, список закрытый.
const NOT_OURS = new Set([
  // Каталог продуктов человека — имена приходят из его дневника.
  'Овощи в обед', 'Овсянка', 'Яблоки', 'Хлеб цельный', 'Орехи',
  '— яблоко', 'и горсть орехов',
  // Значения движка: подсказка «чем добрать», причины риска, вывод по дню.
  'Клетчатка отстаёт на два приёма', 'Вода 63 % от ожидаемого',
  'Сон 6,2 ч — ниже нормы',
  // Предложения, собранные подстановкой со словом внутри: скелет их не ловит,
  // потому что подставляется не число, а имя фактора или дня.
  'Чаще всего вниз тянет вода', 'Тренд тянет вверх сон, вниз — вода',
  'Две недели плато — вес стоит с 10 августа',
  'Ложитесь в среднем в 00:40, разброс полтора часа',
  'Суббота — самый слабый день недели',
  'Темп −0,45 кг в неделю — к цели в середине декабря',
  'Цель 84 кг — поставлена с куратором, срок до декабря',
  'кг · −0,4 за неделю',
  // Демо-подписи самого стенда канваса.
  'вс, 9 августа', 'занято 32 из 32', '−1,8 / мес', 'в руке', 'нет места',
  'За месяц → каталог', 'сладкое к кофе', 'обед 13:10'
]);

// Собрано подстановкой, и подставляется не число, а число с единицей или со
// склонением: скелет такие строки не сводит, хотя фраза в коде та же.
const BUILT = new Set([
  'Нужно 4 клетки — освободите место',
  'Обычно вы едите за 1 ч 40 мин до сна',
  'не хватит 78 ккал',
  'г добрать',
  'Между обедом и ужином обычно 6 часов',
  'Вода · 1,7 / 2,7 л'
]);

// Отступления, названные вслух: каждое стоит на строке контракта, на решении
// владельца или на противоречии внутри самого канваса.
const EXCEPTIONS = new Map([
  // Кадр «Разбор · Карта активности» называет лист иначе, чем плитку, из
  // которой он открывается («Тепловая карта · Как сейчас / Серия / Месяц
  // целиком»). Заголовок листа взят от плитки; расхождение — в UI_V4_FINDINGS.
  ['Карта активности', 'лист назван не как плитка, из которой открыт'],
  // Кадр «Каталог · нет места» предлагает вместо снятия виджета выбрать вид
  // поменьше и помечает те, что тоже не влезли. В продукте у заблокированной
  // карточки только подсказка и кнопка снятия; это функция, а не копия.
  ['Месяц целиком · 2×2', 'выбор вида в заблокированном каталоге не построен'],
  ['Как сейчас · 2×1 · тоже нет места', 'то же — вид поменьше не предлагается'],
  // Кадр «Разбор · Качество еды» написан под три части столбика; владелец
  // 30 августа оставил две (сладкое и остальное) до разметки базы.
  ['Цельной еды', 'третья часть столбика ждёт разметки базы'],
  ['После 19:00 обработанного', 'то же решение владельца'],
  ['вдвое больше', 'то же решение владельца'],
  ['Балл считается по доле цельных продуктов в рационе — шкала в справочнике',
    'норма названа честно: движок считает вредность, сладкое — из простых углеводов'],
  // Превью в шторке пишет кикер короче, чем строка «состав дефолта» и кадр
  // Главной: «Тренд · 14 дней» против «Тренд здоровья · 7 дней». Контракта двое.
  ['Тренд · 14 дней', 'контракт и кадр Главной дают полное имя виджета'],
  // Кадр не показывает, откуда у 2×1 берётся «белки, г»: в продукте подпись
  // кольца, а не отдельная строка.
  ['белки, г', 'подпись кольца, отдельной строкой в продукте не стоит']
]);

describe('копия кадров Главной против раздела «Текст кадров дословно»', () => {
  const canvas = fs.readFileSync(CANVAS, 'utf8');
  const frames = readFrameCopy(canvas);
  const source = SOURCES.map((f) => fs.readFileSync(path.join(WEB, f), 'utf8')).join('\n');
  const sourceSkeleton = skeleton(source);

  // Подложка Главной повторяется почти в каждом кадре: её слова принадлежат
  // кадру Главной и проверяются там один раз.
  const background = new Set();
  for (const [label, words] of frames) {
    const pure = /^Кнопка настройки · |^Быстрые действия · один пункт · |^Быстрые действия · ни одного$|^Главная · дефолтная раскладка$/;
    if (pure.test(label)) for (const w of words) background.add(w);
  }

  it('раздел «Текст кадров дословно» в канвасе есть', () => {
    expect(canvas).toContain('Текст кадров дословно');
    expect(frames.size).toBeGreaterThanOrEqual(59);
  });

  it('слова кадров произносит и продукт', () => {
    const missing = [];
    for (const [label, words] of frames) {
      const own = [...new Set(words)]
        .filter((w) => !background.has(w) && isWord(w))
        .filter((w) => !NOT_OURS.has(w) && !EXCEPTIONS.has(w) && !BUILT.has(w));
      for (const word of own) {
        if (source.includes(word)) continue;
        if (sourceSkeleton.includes(skeleton(word))) continue;
        missing.push(`${label}: «${word}»`);
      }
    }
    expect(missing).toEqual([]);
  });

  it('счёт плиток в карточке сброса совпадает с составом дефолта', () => {
    // Кадр отставал от собственного контракта и говорил «Одиннадцать» при
    // тринадцати в составе — расхождение поймала именно сверка слов.
    const core = fs.readFileSync(path.join(WEB, 'heys_widgets_core_v1.js'), 'utf8');
    const layout = core.slice(core.indexOf('const DEFAULT_LAYOUT'), core.indexOf('SHRINK_ALLOWED_REASONS'));
    const count = (layout.match(/^\s{6}type: '/gm) || []).length;
    expect(count).toBe(13);
    expect(fs.readFileSync(path.join(WEB, 'heys_widgets_ui_v1.js'), 'utf8'))
      .toContain('Тринадцать плиток в порядке');
  });

  it('осознанные отступления не разрослись', () => {
    expect(EXCEPTIONS.size).toBe(9);
    expect(NOT_OURS.size).toBe(26);
    expect(BUILT.size).toBe(6);
  });
});
