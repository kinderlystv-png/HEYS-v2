// Строки «текст» раздела: метка кадра → слова по порядку.
function readFrameCopy(source) {
  const frames = new Map();
  const re = /<div class="spec"[^>]*><b>([^<]+) · текст<\/b><span data-v="([^"]*)"/g;
  let m;
  while ((m = re.exec(source))) frames.set(m[1], m[2].split(' › '));
  return frames;
}

// Кадры `data-demo="protocol"` — протокол сравнения, по ним не реализовывать
// (правило проекта; сам канвас повторяет его словами над блоком калорий).
// Их копия к продукту не относится: он говорит словами выбранного кадра.
function readProtocolFrames(source) {
  const labels = new Set();
  const re = /data-demo="protocol"[^>]*data-screen-label="([^"]+)"/g;
  let m;
  while ((m = re.exec(source))) labels.add(m[1]);
  return labels;
}

// Число в кадре — демо-данные, в коде на его месте подстановка. Сравниваем
// скелет: цифры и `${...}` схлопываются в один знак вместе с пробелами вокруг.
function skeleton(text) {
  return text
    .replace(/\$\{[^}]*\}/g, '#')
    .replace(/[\d ]+(?:[  ,.:]\d+)*/g, '#')
    .replace(/\s*#\s*/g, '#')
    .replace(/#+/g, '#')
    .replace(/\s+/g, ' ')
    .trim();
}

