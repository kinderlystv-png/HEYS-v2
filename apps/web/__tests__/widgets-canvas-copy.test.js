describe('копия кадров Главной против раздела «Текст кадров дословно»', () => {
  const canvas = fs.readFileSync(CANVAS, 'utf8');
  const frames = readFrameCopy(canvas);
  const protocolFrames = readProtocolFrames(canvas);
  const source = SOURCES.map((f) => fs.readFileSync(path.join(WEB, f), 'utf8')).join('\n');
  const sourceSkeleton = skeleton(source);

  // Подложка Главной повторяется почти в каждом кадре: её слова принадлежат
  // кадру Главной и проверяются там один раз.
  //
  // Кадр-источник в набор подложки не входит — иначе его собственные слова
  // отфильтровываются и не проверяются нигде. Эта дыра прятала «Долгое
  // нажатие — взять виджет»: подпись подвала расстановки, которой в продукте
  // нет и по контракту быть не должно.
  const BACKGROUND_SOURCE = 'Главная · дефолтная раскладка';
  const background = new Set();
  for (const [label, words] of frames) {
    const pure =
      /^Кнопка настройки · |^Быстрые действия · один пункт · |^Быстрые действия · ни одного$/;
    if (pure.test(label)) for (const w of words) background.add(w);
  }
  for (const w of frames.get(BACKGROUND_SOURCE) || []) background.add(w);

  it('раздел «Текст кадров дословно» в канвасе есть', () => {
    expect(canvas).toContain('Текст кадров дословно');
    expect(frames.size).toBeGreaterThanOrEqual(59);
  });

  it('протокольные кадры канваса найдены и названы поимённо', () => {
    // Пустой набор превратил бы фильтр ниже в молчаливое «не смотрели»:
    // разметка кадров сменится — тест обязан упасть, а не пропустить.
    expect([...protocolFrames].sort()).toEqual(
      [
        'Главная · ряд занят целиком',
        'Главная · хвост одна клетка',
        'Добавление · 1 колонка',
        'Добавление · 2 колонки',
        'Добавление · 3 колонки',
        'Добавление · 4 колонки',
        'Калории без заголовка · Максимум цифры',
        'Калории без заголовка · Один факт',
        'Калории без заголовка · Подписи над числами',
        'Калории без заголовка · Строка',
        'Кнопка настройки · 40 малая',
        'Кнопка настройки · 48 обводка',
        'Кнопка настройки · 48 шалфей',
      ].sort(),
    );
  });

  it('слова кадров произносит и продукт', () => {
    const missing = [];
    for (const [label, words] of frames) {
      if (protocolFrames.has(label)) continue;
      const own = [...new Set(words)]
        .filter((w) => (label === BACKGROUND_SOURCE || !background.has(w)) && isWord(w))
        .filter((w) => !NOT_OURS.has(w) && !EXCEPTIONS.has(w) && !BUILT.has(w));
      for (const word of own) {
        if (source.includes(word)) continue;
        if (sourceSkeleton.includes(skeleton(word))) continue;
        missing.push(`${label}: «${word}»`);
      }
    }
    expect(missing).toEqual([]);
  });

  it('счёт плиток в карточке сброса совпадает с составом дефолта', () => {
    // Кадр отставал от собственного контракта и говорил «Одиннадцать» при
    // тринадцати в составе — расхождение поймала именно сверка слов.
    const core = fs.readFileSync(path.join(WEB, 'heys_widgets_core_v1.js'), 'utf8');
    const layout = core.slice(
      core.indexOf('const DEFAULT_LAYOUT'),
      core.indexOf('SHRINK_ALLOWED_REASONS'),
    );
    const count = (layout.match(/^\s{6}type: '/gm) || []).length;
    expect(count).toBe(13);
    expect(fs.readFileSync(path.join(WEB, 'heys_widgets_ui_v1.js'), 'utf8')).toContain(
      'Тринадцать плиток в порядке',
    );
  });

  it('осознанные отступления не разрослись', () => {
    expect(EXCEPTIONS.size).toBe(15);
    expect(NOT_OURS.size).toBe(28);
    expect(BUILT.size).toBe(11);
  });
});
