// Копия кадров Главной против раздела канваса «Текст кадров дословно».
// Раздел даёт слова каждого кадра по порядку сверху вниз; здесь проверяется,
// что слова, которые продукт обязан произнести сам, в коде есть.
//
// Почему отдельно от геометрии: расхождение в словах не ловит ни один гейт по
// числам, а человек читает именно слова. Так нашлось «Одиннадцать плиток» при
// тринадцати в составе и «сб — самый слабый день недели» вместо «Суббота».
