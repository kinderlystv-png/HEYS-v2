// Масштаб версии D — то, что нельзя потерять при правках.
//
// Заголовки секций адаптивные и ниже ~1150px падают до минимума `clamp`. Всё
// крупное внутри секций обязано падать вместе с ними: замер 2026-08-08 на 440px
// показывал цену «0 ₽» в 2.00 от заголовка секции, «7 990» — 1.40, акцентную
// строку — 0.77. Читалось это не как «крупный шрифт», а как отсутствие
// иерархии: на средних ширинах всё сползалось в одну кучу крупного.
//
// Правило записано рядом с `ClosingLine` в `versions/d/primitives.tsx`, но
// комментарий не останавливает правку — остановить может только падающий тест.
// Регресс здесь выглядит безобидно: кто-то пишет `text-[24px]` для нового
// подзаголовка, на своём широком экране видит нормальную картину и уходит. На
// 440px этот размер молча сравняется с заголовком секции.
//
// Тест читает исходники, а не рендерит их: правило про запись размера, и такая
// проверка не должна падать из-за окружения (`next/font`, jsdom, разметка).

import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

const D_DIR = path.resolve(__dirname, '../versions/d');
const QUIZ_FILE = path.resolve(__dirname, '../quiz/TrialQuiz.tsx');

/**
 * Порог, с которого размер начинает спорить с заголовком секции. Заголовки
 * секций на узких экранах опускаются до 30px, и порог откалиброван замером на
 * этой ширине, а не выбран на глаз: 17px давало 0.57 от заголовка, 18px — 0.60,
 * то есть ровно здоровую долю подзаголовка, и эти размеры при разборе
 * 2026-08-08 править не пришлось. Ломаться начиналось с 20px (0.67) и дальше
 * вверх — 22px «Антон» 0.73, акцентная строка 0.77, цены 1.40 и 2.00.
 *
 * Первая версия теста стояла на 17 и ловила два безобидных заголовка. Порог
 * поднимать выше 20 нельзя: именно 20px был первым размером, который пришлось
 * переводить на адаптивный.
 */
const FLUID_REQUIRED_FROM = 20;

/**
 * Размеры, которым адаптивность не нужна, — с причиной для каждого. Список
 * намеренно точечный, а не «пропустить файл целиком»: новое нарушение в том же
 * файле обязано ловиться.
 */
const ALLOWED: ReadonlyArray<{ file: string; size: number; why: string }> = [
  {
    file: 'primitives.tsx',
    size: 44,
    why: 'декоративный номер секции: полупрозрачный фон, не читаемый текст и не участвует в иерархии',
  },
  {
    file: 'NavD.tsx',
    size: 22,
    why: 'глиф кнопки закрытия в мобильном меню — иконка, а не текст',
  },
  {
    file: 'FooterD.tsx',
    size: 32,
    why: 'подпись «HEYS» в подвале: заливка прозрачная, виден только контур в 10 % белого, aria-hidden — фон подвала, а не строка иерархии',
  },
];

const isAllowed = (file: string, size: number) =>
  ALLOWED.some((entry) => entry.file === file && entry.size === size);

const sourceFiles = () => [
  ...readdirSync(D_DIR)
    .filter((name) => name.endsWith('.tsx'))
    .map((name) => ({ name, full: path.join(D_DIR, name) })),
  { name: 'TrialQuiz.tsx', full: QUIZ_FILE },
];

describe('масштаб версии D', () => {
  it('крупные размеры заданы через clamp, а не фиксированным px', () => {
    const offenders: string[] = [];

    for (const { name, full } of sourceFiles()) {
      const source = readFileSync(full, 'utf8');

      // Внутренности `clamp(...)` вырезаются перед поиском: там фиксированные
      // значения и есть предмет правила — это границы диапазона, а не жёсткий
      // размер.
      const withoutClamps = source.replace(/clamp\([^)]*\)/g, 'clamp(…)');

      for (const match of withoutClamps.matchAll(/text-\[(\d+(?:\.\d+)?)px\]/g)) {
        const size = Number(match[1]);
        if (size < FLUID_REQUIRED_FROM || isAllowed(name, size)) continue;
        offenders.push(`${name}: text-[${size}px]`);
      }
    }

    expect(
      offenders,
      offenders.length
        ? `Фиксированный размер ≥ ${FLUID_REQUIRED_FROM}px не сожмётся вместе с заголовком секции и на узких ` +
            'экранах сравняется с ним. Задайте его через clamp(минимум, Nvw, максимум): максимум — как в ' +
            'прототипе, минимум — 0.55–0.60 от заголовка для подзаголовков и 0.60–0.65 для акцентных строк. ' +
            `Если размер действительно вне иерархии — добавьте его в ALLOWED с причиной.\n  ${offenders.join('\n  ')}`
        : undefined,
    ).toEqual([]);
  });

  it('у каждого исключения указана причина, а сам список не разрастается', () => {
    for (const entry of ALLOWED) {
      expect(
        entry.why.length,
        `${entry.file} ${entry.size}px — причина слишком короткая`,
      ).toBeGreaterThan(30);
    }
    // Разросшийся список исключений означает, что правило перестало
    // действовать, а тест — ловить.
    expect(ALLOWED.length).toBeLessThanOrEqual(6);
  });
});
