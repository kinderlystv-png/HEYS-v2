// fonts.ts — типографика версии B.
//
// Spectral выбран владельцем (2026-08-01) после живого сравнения через
// переключатель шрифта: спокойная антиква с кириллицей, ближе к дисплейному
// характеру Future, чем текущий гротеск, но не такая хрупкая, как Cormorant.
// Self-host через `next/font` — внешних CDN-запросов в runtime нет, это
// требование CSP лендинга.
//
// Компенсация размера. У Spectral заметно меньшая высота строчных: замер в
// браузере даёт 0.45em против 0.535em у Open Sans, то есть при одинаковом
// кегле он выглядит примерно на 19 % мельче. Вместо правки десятков размеров
// по всей версии применяется `font-size-adjust`: браузер сам подгоняет кегль
// так, чтобы высота строчных совпала с прежней. Значение — измеренная высота
// строчных Open Sans.

import { Spectral } from 'next/font/google';

export const versionBFont = Spectral({
  subsets: ['cyrillic', 'latin'],
  weight: ['400', '500', '600', '700'],
  display: 'swap',
});

/**
 * Высота строчных Open Sans — цель, к которой подгоняется кегль Spectral.
 * Строкой, а не числом: числовые значения React прогоняет через свой список
 * безразмерных свойств, и `font-size-adjust` в нём нет — получалось `0.535px`,
 * то есть недопустимое значение, и правило молча отбрасывалось.
 */
export const VERSION_B_FONT_SIZE_ADJUST = '0.50';
