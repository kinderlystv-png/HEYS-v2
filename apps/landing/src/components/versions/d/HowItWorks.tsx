// почему так» сняты: всё это уже сказано выше на странице (секции 02 и 04), а
// здесь разбавляло сильные факты — десять строк уравнивали их со слабыми.
//
// Строки с ценой тут больше нет. Цена живёт в карточке тарифа, а сравнение —
