// 01 — «Ваша ситуация» (`#pain`).
//
// Блок узнавания: четыре ситуации без карточек и иконок, затем вывод о том, что
// дело не в силе воли. Карточку заявки сюда не ставим: COPY_VOICE 2026-06-27 —
// первая заявка после объяснения и доказательства, не сразу после узнавания.
// Trial-карточка стоит после артефакта недели (`ReviewedWeek`).

import { ClosingLine, Section } from './primitives';

const SITUATIONS = [
  'Вес стоит, и непонятно, почему — вроде бы питаетесь нормально',
  'Советы «для всех» не подходят: у вас поездки, поздние ужины и общий стол с семьёй',
  'Начинаете диету — держитесь 2 недели — срываетесь — вините себя',
  'Пробовали приложения — бросили через неделю, потому что надоело всё считать',
];

export default function PainSection() {
  return (
    <Section id="pain" index="01" label="Ваша ситуация" tone="white">
      {/* Заголовок крупнее общего `SectionTitle`: в прототипе
          (`design/landing-d/prototype.html` строка 223) у секций 01 и 02 размер
          `clamp(30px,3.8vw,46px)` против `clamp(30px,3.8vw,44px)` у 04–06 — так
          первые две секции нарастают по весу. Размер задан локальным классом:
          `primitives.tsx` общий для всех секций. */}
      <h2
        data-reveal
        className="mt-[54px] text-balance text-center text-[clamp(30px,3.8vw,46px)] font-semibold leading-[1.18] tracking-[-0.02em] text-[#101826]"
      >
        Знакомо?
      </h2>

      <ul data-reveal className="mx-auto mt-12 max-w-[760px]">
        {SITUATIONS.map((text, i) => (
          <li
            key={text}
            className="grid grid-cols-[44px_1fr] gap-[18px] border-b border-[rgba(16,24,38,0.12)] px-1 py-[22px] first:border-t"
          >
            <span className="pt-1 text-[11px] font-semibold tracking-[0.16em] text-[color:var(--da)]">
              {String(i + 1).padStart(2, '0')}
            </span>
            {/* 15.5px, не 17px как раньше: список из четырёх пунктов не должен
                визуально спорить с выводом блока ниже — там теперь крупная
                полужирная строка-УТП, и пункты узнавания при таком же весе
                перетягивали внимание на себя. Решение владельца 2026-08-08. */}
            <span className="text-[15px] leading-[1.5] text-[#101826]">{text}</span>
          </li>
        ))}
      </ul>

      <ClosingLine
        lead="Сила воли тут ни при чём."
        accent="Рядом нужен человек, которому не всё равно."
      />

      {/* Переход, а не заявка. Карточку заявки сюда не возвращаем (см. шапку
          файла), но и упирать человека в следующий заголовок без действия
          нельзя. Поэтому текстовая ссылка, а не кнопка-плашка: она не должна
          спорить с главным действием страницы («Бесплатная неделя Pro»).
          `min-h-[44px]` — минимальная область нажатия, требование доступности.
          Без подчёркивания и без границы — обе версии не понравились: линия
          под двумя строками читалась как случайный разделитель, а не как
          обозначение ссылки. Кликабельность держат три сигнала: цвет темнеет
          на hover, стрелка синяя и сама сдвигается — этого достаточно для
          тихого вторичного действия, которое не должно быть заметнее ссылки. */}
      {/* Прижата к низу секции, а не подвешена сразу под выводом: это переход
          к следующему блоку, и стоять он должен на границе между секциями.
          Секция даёт `pb-[104px]`, поэтому отрицательный отступ снизу
          подтягивает ссылку ближе к стыку, оставляя воздух над ней. */}
      <div data-reveal className="mb-[-56px] mt-24 text-center">
        <a
          href="#curator"
          className="group inline-block min-h-[44px] py-1 text-[15px] leading-[1.5] text-[#5B6472] transition-colors duration-[250ms] hover:text-[#101826]"
        >
          {/* Переносы вручную — на мобильном фраза делится на три ровных
              куска вместо случайного переноса посреди слов, а стрелка уходит
              отдельной строкой вниз: так она читается завершающим жестом, а не
              довеском к последнему слову. На экранах шире 640px оба переноса
              скрыты — фраза и стрелка помещаются в одну строку. */}
          Если узнали себя — посмотрите,
          <br className="sm:hidden" /> как это устроено
          <br className="sm:hidden" />
          {/* Стрелка вниз, не вправо: на мобильном она стоит отдельной
              строкой под текстом, и «→» там читался бы рассинхроном — фраза
              ведёт взгляд вниз, к следующему блоку, а не в сторону. На `sm+`,
              где перенос скрыт и стрелка возвращается в конец строки, тот же
              глиф остаётся уместным — она по-прежнему указывает «дальше», а не
              обещает горизонтальное движение. */}
          <span
            aria-hidden="true"
            className="inline-block text-[color:var(--da)] transition-transform duration-[250ms] group-hover:translate-y-0.5 sm:ml-1"
          >
            ↓
          </span>
        </a>
      </div>

      {/* «Рядом» здесь — описание потребности человека, а не обещание
          доступности куратора: разделение прямо закреплено в COPY_VOICE
          (раздел «Зависит от контекста»). */}
    </Section>
  );
}
