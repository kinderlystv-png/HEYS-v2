// landing-versions.ts — реестр версий лендинга для личного выбора владельца.
//
// Задача `22` п. 3.17, план — `маркетинг/46`. Версии существуют, чтобы
// владелец мог открыть их подряд и выбрать, какая идёт в работу:
//   A — страница-объяснение (прежняя основная, baseline для сравнения);
//   B — нарратив по образцу Future (`маркетинг/45`);
//   C — эталонная «страница-решение» (`маркетинг/46`);
//   D — версия «вникание» (решение `15` №50, канон — `design/landing-d/`).
//
// ВАЖНО: это НЕ эксперимент на посетителях. Публика всегда получает основную
// версию (`DEFAULT_VERSION`); остальные лежат на отдельных роутах `/v/…` и не
// связаны ссылками с публичной страницей. Распределения по вариантам нет и не
// планируется до отдельного решения владельца о публичном A/B (`22` п. 3.2).
//
// Основная версия сменилась 2026-08-09: `A` → `D`. Роль «в корне» кочует между
// версиями, поэтому пути живут в `VERSION_PATHS`, а не зашиты по месту: смена
// основной — правка одной таблицы и двух страниц, а не поиск ссылок по всему
// проекту.
//
// Файл намеренно отделён от `landing-variants.ts`: тот описывает контент
// варианта A и сейчас развивается параллельно (меню, nav-подсказки). Здесь —
// только реестр версий и разбор параметра, без пересечения зон правки.

export const LANDING_VERSIONS = ['A', 'B', 'C', 'D'] as const;

export type LandingVersion = (typeof LANDING_VERSIONS)[number];

/**
 * Версия, которую видит публичный посетитель без явной ссылки.
 *
 * С 2026-08-09 это `D` (решение владельца): она доведена по дизайн-пакетам и
 * заменяет `A` в корне. `A` не удалена — переехала на `/v/a/` и осталась
 * доступной через переключатель наравне с `B` и `C`.
 */
export const DEFAULT_VERSION: LandingVersion = 'D';

// Лендинг собирается как статический экспорт (`output: 'export'`), поэтому
// выбор версии через query-параметр невозможен: `searchParams` на сервере
// недоступен, а класть все версии в один HTML нельзя — черновики оказались бы
// в разметке публичной страницы. Каждая версия — отдельный статический роут.
const VERSION_PATHS: Record<LandingVersion, string> = {
  A: '/v/a/',
  B: '/v/b/',
  C: '/v/c/',
  D: '/',
};

/** Путь версии. Основная версия живёт в корне, черновики — в `/v/…`. */
export function versionPath(version: LandingVersion): string {
  return VERSION_PATHS[version];
}

export interface LandingVersionMeta {
  id: LandingVersion;
  /** Короткое имя для переключателя владельца. */
  label: string;
  /** Чем версия отличается по замыслу — подсказка в переключателе. */
  hint: string;
}

