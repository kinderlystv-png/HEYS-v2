-- 2026-08-02 — содержательные исправления состава в общем каталоге.
--
-- Значения взяты из справочного состава продуктов; для брендовых позиций —
-- типичные для категории и для заявленной жирности. Жирнокислотный состав
-- разложен по долям, характерным для сырья (свиной жир ~39% насыщенных,
-- подсолнечное масло ~11%, молочный жир ~65%).
--
-- Калорийность считается формулой проекта: 3*белок + 4*углеводы + 9*жир.
-- Она даёт значения ниже стандартных таблиц, потому что белок намеренно
-- учитывается по 3 ккал/г (NET-Atwater) — это не ошибка пересчёта.
--
-- ── Алкоголь ───────────────────────────────────────────────────────────────
-- В модели нет поля для этанола, а он даёт 7 ккал/г — у вина это две трети
-- калорийности. Поэтому энергия спирта закладывается в сложные углеводы по
-- эквиваленту 7/4 = 1.75 г на грамм спирта. Выбраны именно сложные, а не
-- сахара: так спирт не попадает в оценку сахарной нагрузки и гликемические
-- расчёты. В description у каждой позиции это указано явно.
-- Это компромисс ради верной калорийности; отдельное поле для этанола —
-- следующий шаг, он требует правки формулы в клиенте, сервере и MCP.

BEGIN;

-- ── Потерянный жир ─────────────────────────────────────────────────────────

-- Сало солёное: было 43 г жира, реально ~89 (шпик — почти чистый жир).
UPDATE public.shared_products
SET protein100 = 2.4, simple100 = 0, complex100 = 0,
    badfat100 = 35, goodfat100 = 54, fiber100 = 0, gi = 0, harm = 5.5
WHERE id = '90dca660-6067-449a-adb5-7771407b0a0b';           -- → ~808 ккал

-- Чипсы Lay's: было 14 г жира, реально ~34. Вредность 1.4 — инверсия.
UPDATE public.shared_products
SET protein100 = 6.3, simple100 = 0.5, complex100 = 50,
    badfat100 = 4, goodfat100 = 30, fiber100 = 4.4, gi = 56, harm = 7.5
WHERE id = '306184bf-d3f4-4ee9-b887-5b2fedc79efd';           -- → ~527 ккал

-- Говяжий антрекот: 3.1 г жира у самого жирного отруба говядины.
UPDATE public.shared_products
SET protein100 = 27, simple100 = 0, complex100 = 0,
    badfat100 = 7.5, goodfat100 = 10.5, gi = 0, harm = 2.5
WHERE id = '25313728-9a60-4a9b-99b9-ce6d36387548';           -- → ~243 ккал

-- Сосиски «Вязанка Сливочные»: жир 13.5 → ~22.
UPDATE public.shared_products
SET protein100 = 11, simple100 = 0.5, complex100 = 1.5,
    badfat100 = 9, goodfat100 = 13, gi = 0
WHERE id = '0d389499-e882-4a60-85a3-56d92d359667';           -- → ~239 ккал

-- Доширак: углеводы по сухому продукту, а жир нет — лапша обжарена в масле.
UPDATE public.shared_products
SET protein100 = 9, simple100 = 3, complex100 = 57,
    badfat100 = 9.5, goodfat100 = 9.5, fiber100 = 1, gi = 60, harm = 7.5
WHERE id = 'cd4662ce-ddb1-4593-8c9d-d7d819f2d875';           -- → ~438 ккал

-- Лосось слабосолёный: жир вдвое занижен; harm 6.3 — инверсия для жирной рыбы.
UPDATE public.shared_products
SET protein100 = 21, badfat100 = 3, goodfat100 = 11, gi = 0, harm = 2.0
WHERE id = 'a28afeab-6f43-42b9-941e-d81d74f7b646';           -- → ~189 ккал

-- Запечённое мясо с картошкой: насыщенные 0 при сметане и сыре в составе.
UPDATE public.shared_products
SET protein100 = 12, simple100 = 0.8, complex100 = 8.1,
    badfat100 = 4, goodfat100 = 5, fiber100 = 1.2, gi = 55, harm = 2.0
WHERE id = '5d66f31b-9477-4744-9683-007aab31bdaf';           -- → ~153 ккал

-- Сэндвич-ролл: потеряна углеводная основа (лаваш).
UPDATE public.shared_products
SET protein100 = 11, simple100 = 2, complex100 = 24,
    badfat100 = 3.5, goodfat100 = 6, fiber100 = 1.5, gi = 60
WHERE id = '4e01308d-559a-429a-86f8-262e8e41da53';           -- → ~223 ккал

-- Творожный сыр 60%: жир был как у 30-процентного.
UPDATE public.shared_products
SET protein100 = 6, simple100 = 3, complex100 = 0,
    badfat100 = 18, goodfat100 = 10, gi = 15
WHERE id = 'ce509fc1-2ae1-4e85-9f6e-ede05b15ef91';           -- → ~282 ккал

-- Сырники: белок 5 г при твороге в основе.
UPDATE public.shared_products
SET protein100 = 13, simple100 = 10, complex100 = 8,
    badfat100 = 4, goodfat100 = 5, fiber100 = 0.5, gi = 65
WHERE id = '20a83021-0073-4a42-8dcb-891c550902fe';           -- → ~192 ккал

-- ── Перепутаны сахара и крахмал ────────────────────────────────────────────

-- Ананасы в собственном соку: 10 г жира и 0.7 г сахаров — значения не от
-- этого продукта. ГИ 10 тоже занижен.
UPDATE public.shared_products
SET protein100 = 0.4, simple100 = 12, complex100 = 0,
    badfat100 = 0, goodfat100 = 0.1, fiber100 = 1, gi = 55, harm = 2.0
WHERE id = '0a1ab62a-f917-408c-a068-49a93472d4e9';           -- → ~50 ккал

-- Хлеб белый: сахаров 28 г при крахмале 21 — перевёрнуто.
UPDATE public.shared_products
SET simple100 = 4, complex100 = 45
WHERE id = 'fa736af9-1a9b-43e7-b2c6-3430bb41b4d3';           -- калорийность та же

-- ── Название против данных ─────────────────────────────────────────────────

-- Меренга: 60 г сахаров при «(без сахара)» в названии. Данные соответствуют
-- обычной меренге, поэтому убирается вводящая в заблуждение приписка.
UPDATE public.shared_products
SET name = 'Яблочная меренга с ягодами',
    name_norm = 'яблочная меренга с ягодами'
WHERE id = '490a7127-3355-48f3-a13a-878eed571246';

-- ── Алкоголь: энергия этанола через эквивалент в сложных углеводах ─────────

-- Красное вино полусладкое: ~10.5 г спирта + ~5 г сахара.
-- 10.5 * 7 = 73.5 ккал → 73.5 / 4 = 18.4 г эквивалента.
UPDATE public.shared_products
SET simple100 = 5, complex100 = 18.4, gi = 0, harm = 6.0,
    description = 'Калорийность включает энергию спирта (~10.5 г/100 мл), внесённую эквивалентом в сложные углеводы: поля для этанола в модели нет.'
WHERE id = 'a3289123-a5e4-4b01-9eef-c5056c7fdc74';           -- → ~94 ккал

-- Bakalář пиво: ~4 г спирта + 3.5 г углеводов.
-- 4 * 7 = 28 ккал → 28 / 4 = 7 г эквивалента, итого 10.5.
UPDATE public.shared_products
SET complex100 = 10.5, gi = 0, harm = 5.0,
    description = 'Калорийность включает энергию спирта (~4 г/100 мл), внесённую эквивалентом в сложные углеводы: поля для этанола в модели нет.'
WHERE id = 'cb77557e-55c0-43c2-ae49-4484c3707214';           -- → ~42 ккал

-- Жигулёвское пшеничное: ~4.2 г спирта + 6 г углеводов.
-- 4.2 * 7 = 29.4 ккал → 29.4 / 4 = 7.35 г эквивалента, итого 13.35.
UPDATE public.shared_products
SET complex100 = 13.35, gi = 0, harm = 5.0,
    description = 'Калорийность включает энергию спирта (~4.2 г/100 мл), внесённую эквивалентом в сложные углеводы: поля для этанола в модели нет.'
WHERE id = '9a30644b-96a2-4cdf-852f-a1b003bc0447';           -- → ~53 ккал

COMMIT;

