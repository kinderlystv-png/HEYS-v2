-- 2026-08-02 — правки каталога, доказуемые арифметикой и физикой продукта.
--
-- Продолжение чистки каталога перед релизом. Сюда попадает ТОЛЬКО то, где
-- вывод следует из самих данных, а не из знания конкретной этикетки.
-- Содержательные правки (занижен жир у сала и чипсов, перепутаны сахара и
-- крахмал, неучтённый алкоголь) остаются владельцу — см. отчёт ревью.
--
-- ── 1. Клетчатка посчитана дважды ──────────────────────────────────────────
-- Признак: сумма макронутриентов и клетчатки превышает 100 г на 100 г, чего
-- быть не может. Причина: в «сложные углеводы» занесены ОБЩИЕ углеводы, в
-- которые клетчатка уже входит, и она же продублирована отдельным полем.
-- Лечение: вычесть клетчатку из сложных углеводов.
--   Какао-порошок: сумма 123.5 г → 90.5 г, 407 → ~275 ккал
--   Грецкий орех:  сумма 100.8 г →  94.1 г, 687 → ~660 ккал
-- Обе величины после правки оставляют разумное место под влагу и золу.
--
-- ── 2. Трансжиры без насыщенных ────────────────────────────────────────────
-- Промышленные трансжиры образуются при гидрогенизации и всегда идут вместе с
-- насыщенными. Транс > 0 при насыщенных ровно 0 — внутреннее противоречие.
--
-- ── 3. Заметные трансжиры у цельных продуктов ──────────────────────────────
-- В орехах, семечках, рыбе, яйцах, крупах и овощах трансжиров практически нет
-- (< 0.1 г). Значения 0.5–2 г там физически невозможны: у миндаля стоит 1.6,
-- у семечек и кильки 2, у лосося 1.5. Порог 0.5 г выбран намеренно — мелкие
-- значения у составных блюд (майонез, лаваш) правдоподобны и не трогаются.
-- Источник этих цифр — ручное заполнение: в схеме MCP-инструмента правило
-- «trans100 — 0, если не указано» задано явно, то есть код их не порождает.
--
-- На калорийность пункты 2 и 3 не влияют (трансжиры не входят в формулу), но
-- влияют на оценку вредности и рекомендации.
--
-- ПРОВЕРКА ДО:
--   SELECT count(*) FROM shared_products
--    WHERE (protein100+simple100+complex100+badfat100+goodfat100+fiber100) > 100;  -- 2
--   SELECT count(*) FROM shared_products WHERE trans100 > 0 AND badfat100 = 0;     -- 2

BEGIN;

-- 1. Убрать двойной учёт клетчатки.
UPDATE public.shared_products
SET complex100 = GREATEST(complex100 - fiber100, 0)
WHERE (protein100 + simple100 + complex100 + badfat100 + goodfat100 + fiber100) > 100
  AND fiber100 > 0
  AND complex100 >= fiber100;

-- 2. Трансжиры без насыщенных — противоречие.
UPDATE public.shared_products
SET trans100 = 0
WHERE trans100 > 0 AND badfat100 = 0;

-- 3. Заметные трансжиры у цельных натуральных продуктов.
UPDATE public.shared_products
SET trans100 = 0
WHERE trans100 >= 0.5
  AND name ~* '(миндаль|фундук|кешью|фисташк|грецк|орех|семечк|семена|лосось|тунец|минтай|сельдь|селёдк|килька|скумбри|форел|креветк|кальмар|треск|желток|омлет|яйцо|огурец|томат|капуст|морков|свёкл|шпинат|яблок|банан|груш|апельсин|клубник|малин|черник|греч|овсян|перлов|булгур|киноа|фасол|горох|чечевиц)'
  AND name !~* '(батончик|десерт|печень|шоколад|конфет|панировк|сэндвич|гренк|заправк|соус|колбас|паштет|окрошк|пицц|бургер|вафл|торт|пирож|булк|хлеб|урбеч|напиток|начос|шаурм|рулетик|основа)';

COMMIT;

