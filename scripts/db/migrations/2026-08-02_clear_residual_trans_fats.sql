-- 2026-08-02 — остаточные фантомные трансжиры у цельных продуктов.
--
-- Первый проход срезал только значения >= 0.5 г, диапазон 0.05–0.4 был оставлен
-- как правдоподобный. Уточнение: трансжиры ВХОДЯТ в жир и дают 9 ккал/г
-- (heys_models_v1.js: fat = badFat + goodFat + trans), то есть это не
-- бесплатная метка, а завышение калорийности. У цельных продуктов — орехов,
-- рыбы, овощей, фруктов, круп, яиц, свежего мяса и птицы — источника
-- трансжиров нет вовсе, поэтому обнуляются любые значения.
--
-- Не трогается переработка, где источник реален: маргарин, фритюр, кондитерка,
-- колбасы, панировка, соусы — они исключены по названию.
BEGIN;

UPDATE public.shared_products SET trans100 = 0
WHERE trans100 > 0
  AND name ~* '(миндаль|фундук|кешью|фисташк|грецк|орех|семечк|семена|чиа|лосось|тунец|минтай|треск|сельдь|селёдк|килька|скумбри|горбуша|креветк|кальмар|краб|икра|огурец|томат|капуст|морков|свёкл|кабач|перец|шпинат|салат айсберг|брокколи|фасоль|горошек|яблок|банан|груш|апельсин|мандарин|киви|виноград|клубник|малин|черник|голубик|ананас|манго|финик|курага|изюм|авокадо|греч|овсян|рис |киноа|булгур|перлов|чечевиц|яйцо|яйца|белок яйца|желток|курин|индейк|свинин|говядин|стейк|шашлык)'
  AND name !~* '(батончик|печень|торт|пирожн|конфет|шоколад|вафл|десерт|маргарин|фритюр|чипс|начос|наггетс|панировк|колбас|сосиск|котлет|соус|майонез|заправк|мороженое|пломбир|глазированн|сдоб|булк|круассан|гренк|сухарик|кекс)';

COMMIT;
