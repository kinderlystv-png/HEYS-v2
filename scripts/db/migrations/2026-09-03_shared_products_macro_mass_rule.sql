-- 2026-09-03 — масса общего каталога: отдельное правило для БЖУ и для клетчатки.
--
-- ЗАЧЕМ
-- 13.08 карточка «Клетчатка яблочная MEDUTEUT» (белок 5, сахара 40, сложные 0,
-- жиры 2, клетчатка 60 — итого 107 г) не прошла shared_products_mass_within_100g
-- из миграции 2026-08-02. Порог 105 был взят как «5 % на округление этикетки»,
-- физического смысла у числа не было, и владелец поставил вопрос: поднимать порог
-- под добросовестные этикетки или менять саму проверку.
--
-- ЧТО ВЫЯСНЕНО
-- 1. Физика. 100 г продукта = белок + жир + углеводы + клетчатка + вода + зола
--    + органические кислоты + этанол, все слагаемые неотрицательны. Значит
--    истинная сумма БЖУ и клетчатки НИКОГДА не превышает 100 г, а равенство
--    достижимо только для безводного беззольного вещества, которого не бывает
--    (белый сахар в каталоге — 99.8). Всё, что выше 100, — артефакт этикетки
--    или ввода, а не состав.
-- 2. Бюджет округления. ТР ТС 022/2011 и EU 1169/2011 округляют каждое
--    объявленное значение: не хуже 0.5 г на поле. Шесть полей дают максимум 3 г.
--    То есть добросовестный артефакт живёт в полосе 100–103 г, и порог 105
--    УЖЕ щедрее, чем позволяет округление. 107 г округлением не объясняется.
-- 3. Данные, два независимых среза. Экспорт общего каталога 2026-04 (288 карточек)
--    и выгрузка прода 2026-08-14 (236 карточек): в обоих полоса 100–105 г ПУСТА,
--    а всё, что выше 105, — уже разобранный мусор, починенный миграциями
--    2026-08-02: семена чиа 123.5 (клетчатка посчитана дважды) и четыре карточки
--    Chika Layers 107.5–109.0 (полиолы записаны в клетчатку, батончик на 250 ккал
--    считался как 186). Поднять порог до 107 значит вернуть в каталог именно этот
--    класс ошибок — от честной этикетки он по хранимым числам неотличим.
-- 4. Сама карточка MEDUTEUT. Яблочная клетчатка — сушёный порошок из выжимок, в
--    нём 8–10 г влаги и около 2 г золы на 100 г. Этикетка на 107 г не оставляет
--    места воде, которая в продукте заведомо есть: недостоверна этикетка, а не
--    проверка. Ручная подгонка клетчатки 60 → 53 в общей базе тоже недостоверна —
--    это число не с этикетки и не из анализа.
--
-- РЕШЕНИЕ
-- Потолок полной массы НЕ поднимаем (105 остаётся). Добавляем второе, более
-- узкое правило на БЖУ без клетчатки: 100 г сухого вещества + 3 г округления.
-- Зачем это нужно:
--   * Клетчатка — единственное поле без перекрёстной проверки: она добавляет
--     массу, но 0 ккал, поэтому shared_products_energy_plausible на неверной
--     клетчатке не срабатывает никогда. Единственный барьер — правило массы,
--     и ослаблять его нельзя.
--   * У БЖУ, наоборот, лишние 5 г запаса не нужны: максимум по обоим срезам —
--     подсолнечное масло 99.9 и сахар 99.8. Сегодня карточка с БЖУ 104 и нулевой
--     клетчаткой (раздутый жир или задвоенные углеводы) проходит обе проверки,
--     хотя такого продукта не существует. Это правило её ловит.
--   * Разделение делает отказ адресным: сработало правило БЖУ — врут макросы;
--     прошло правило БЖУ, но не прошло правило полной массы — вопрос к клетчатке.
--     Раньше обе причины давали один непрозрачный текст про сумму.
-- MEDUTEUT под новыми правилами: БЖУ 47 г — проходит, полная масса 107 г — не
-- проходит, и отказ теперь прямо указывает на клетчатку. Публиковать её в общий
-- каталог по-прежнему нельзя; личная карточка клиента этим CHECK не ограничена
-- (он стоит только на public.shared_products), поэтому путь для такой этикетки —
-- личный продукт либо согласованное с этикеткой значение углеводов.
--
-- СТАРЫЕ ДАННЫЕ
-- Правило только сужает допустимое и ничего не переписывает. Нарушений нет:
-- по обоим срезам максимум БЖУ без клетчатки — 99.9 г, карточек выше 100 г ноль.
-- Проверять перед применением запросом из блока «ПРОВЕРКА ДО».
--
-- ПРОВЕРКА ДО (ожидаем 0, иначе сначала чинить данные — констрейнт не встанет):
--   SELECT count(*) FROM public.shared_products
--    WHERE COALESCE(protein100,0) + COALESCE(simple100,0) + COALESCE(complex100,0)
--        + COALESCE(badfat100,0) + COALESCE(goodfat100,0) > 103;
--
-- Идемпотентность: раннер может применить файл повторно, ADD CONSTRAINT на
-- существующем имени падает — снимаем прежде чем ставить.
ALTER TABLE public.shared_products
  DROP CONSTRAINT IF EXISTS shared_products_macro_mass_within_100g;

ALTER TABLE public.shared_products
  ADD CONSTRAINT shared_products_macro_mass_within_100g CHECK (
    COALESCE(protein100, 0) + COALESCE(simple100, 0) + COALESCE(complex100, 0)
    + COALESCE(badfat100, 0) + COALESCE(goodfat100, 0) <= 103
  );

