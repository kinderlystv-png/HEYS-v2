      // Контекст записи выдаётся сервером отдельным запросом, а нужен в самом
      // конце — в момент сохранения. Прогретый здесь, он ждёт параллельно с
      // чтениями инструмента вместо того, чтобы добавлять свой round-trip к
      // записи. Промис кэшируется на клиента и уже гасит собственную ошибку.
