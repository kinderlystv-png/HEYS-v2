'use strict';

/**
 * heys/6c2031: граница дневниковых суток в MCP совпадает с приложением.
 *
 * До 02.09 порог трёх утра стоял только у чек-ина, а остальные day-инструменты
 * брали календарную дату по Москве. В окне 00:00–03:00 они расходились: приём
 * в 02:00 уезжал в наступивший календарный день, хотя человек и приложение
 * считали его вчерашним. Ошибка была тихой — сервер отвечал ok, а два дня
 * подряд показывали неверные итоги.
 *
 * В приложении эта граница живёт минимум в четырёх местах, все `getHours() < 3`:
 * heys_morning_checkin_v1.js:58, heys_app_shortcuts_v1.js:51,
 * heys_day_bundle_v1.js:7539, heys_day_insulin_wave_data_v1.js:29.
 */

const test = require('node:test');
const assert = require('node:assert/strict');

const { diaryToday, TOOL_SCHEMAS } = require('../lib/tools');

const at = (iso) => diaryToday(Date.parse(iso));

test('ночь до трёх относится к прошедшим суткам', () => {
  assert.equal(at('2026-09-03T00:01:00+03:00'), '2026-09-02');
  assert.equal(at('2026-09-03T02:00:00+03:00'), '2026-09-02');
  assert.equal(at('2026-09-03T02:59:59+03:00'), '2026-09-02');
});

test('с трёх утра начинается новый день', () => {
  assert.equal(at('2026-09-03T03:00:00+03:00'), '2026-09-03');
  assert.equal(at('2026-09-03T03:00:01+03:00'), '2026-09-03');
});

test('день и вечер не съезжают', () => {
  assert.equal(at('2026-09-02T12:00:00+03:00'), '2026-09-02');
  assert.equal(at('2026-09-02T23:59:00+03:00'), '2026-09-02');
});

test('граница считается по Москве, а не по часовому поясу сервера', () => {
  // 23:30 UTC — это уже 02:30 следующего дня в Москве, то есть ещё вчерашние сутки.
  assert.equal(at('2026-09-02T23:30:00Z'), '2026-09-02');
  // 00:30 UTC — 03:30 по Москве, новый день уже начался.
  assert.equal(at('2026-09-03T00:30:00Z'), '2026-09-03');
});

test('переход через месяц не ломается', () => {
  assert.equal(at('2026-10-01T01:00:00+03:00'), '2026-09-30');
  assert.equal(at('2026-10-01T04:00:00+03:00'), '2026-10-01');
});

test('описание поля date больше не обещает календарные сутки', () => {
  const json = JSON.stringify(TOOL_SCHEMAS);
  assert.ok(
    json.includes('сутки идут с 3 утра по Москве'),
    'в описании даты должна быть названа граница дня',
  );
  assert.ok(
    !json.includes('По умолчанию — сегодня по московскому времени'),
    'старая формулировка обещала календарный день и стала неправдой',
  );
});
